/**
 * OpenSCAD source generation.
 *
 * The point of this export is that a user can *open and edit* the result, so
 * it emits idiomatic primitives and operations — `difference`, `union`, `hull`,
 * `cube`, `cylinder`, `sphere` — with the chip parameters hoisted to the top as
 * named variables. Dumping the tessellated mesh as one `polyhedron` would be
 * smaller and faster to render, and completely useless to edit.
 *
 * Channels become chains of `hull()` between consecutive thin cross-sections.
 * That is the standard OpenSCAD idiom for a loft, and it reproduces the same
 * taper the viewport shows.
 */

import { buildAdjacency, edgesFrom } from '../geometry';
import { sampleAtNode, getLoft } from '../loft';
import { slidePocket, withChannelPlane } from './slide';
import { bossFilletMm, LUER_TAPER, specNumber } from '../ports';
import { placeChannel, TRAPEZOID_DRAFT } from './placement';
import { luerLockLayout } from './portGeometry';
import type {
  ChannelGraph,
  ChipParams,
  CrossSection,
  DrainageVent,
  PortNode,
} from '../../types/project';

const f = (n: number): string => {
  const rounded = Math.round(n * 1e4) / 1e4;
  return Number.isInteger(rounded) ? rounded.toFixed(1) : String(rounded);
};

const deg = (tx: number, ty: number): number => (Math.atan2(ty, tx) * 180) / Math.PI;

/** Thin slab thickness for hull stations, mm. */
const SLICE = 0.01;

export interface ScadOptions {
  /**
   * Stations emitted per edge. Every station becomes a hull pair, and OpenSCAD
   * renders hulls slowly, so this is deliberately coarser than the viewport's
   * tessellation.
   */
  stationsPerEdge?: number;
  projectName?: string;
  /**
   * Drainage holes to drill, exactly as the STL gets them. Vents on nodes that
   * are no longer in the graph are skipped, as they are there.
   */
  drainageVents?: DrainageVent[];
}

function sectionAt(
  crossSection: CrossSection,
  x: number,
  y: number,
  z: number,
  angle: number,
  widthMm: number,
  heightMm: number,
): string {
  const place = `translate([${f(x)}, ${f(y)}, ${f(z)}]) rotate([0, 0, ${f(angle)}])`;

  if (crossSection === 'round') {
    // Lay the disc's axis along the path.
    return `${place} rotate([0, 90, 0]) cylinder(h = ${f(SLICE)}, d = ${f(widthMm)}, center = true, $fn = channel_fn);`;
  }

  if (crossSection === 'trapezoid') {
    const topW = widthMm;
    const botW = widthMm * TRAPEZOID_DRAFT;
    // A 4-point prism: wide at the open face, narrower at the floor.
    return (
      `${place} linear_extrude(height = ${f(SLICE)}, center = true) ` +
      `polygon([[${f(-botW / 2)}, ${f(-heightMm / 2)}], [${f(botW / 2)}, ${f(-heightMm / 2)}], ` +
      `[${f(topW / 2)}, ${f(heightMm / 2)}], [${f(-topW / 2)}, ${f(heightMm / 2)}]]);`
    );
  }

  return `${place} cube([${f(SLICE)}, ${f(widthMm)}, ${f(heightMm)}], center = true);`;
}

export function exportScad(
  graph: ChannelGraph,
  params: ChipParams,
  options: ScadOptions = {},
): string {
  const { stationsPerEdge = 10, projectName = 'OpenChip chip' } = options;

  // A slide chip's channels sit on the pocket floor, not on the split plane.
  // Every `split_height` below — the placement calls and the emitted variable
  // alike — reads from a chipParams that already carries that plane, so the
  // OpenSCAD file and the STL cannot drift apart on it.
  const pocket = slidePocket(params);
  const chipParams = withChannelPlane(params);
  const loft = getLoft(graph, chipParams);
  const adjacency = buildAdjacency(graph.edges);

  const out: string[] = [];
  const w = (line = '') => out.push(line);

  // --- header ---------------------------------------------------------------
  w(`// ${projectName}`);
  w('// Generated by OpenChip. All dimensions in millimetres.');
  w('//');
  w('// Edit the parameters below and re-render. The channel network is');
  w('// subtracted from the chip block, so growing a channel removes material.');
  w();
  w('/* [Chip] */');
  w(`chip_width = ${f(chipParams.width)};`);
  w(`chip_length = ${f(chipParams.length)};`);
  w(`base_thickness = ${f(chipParams.baseThickness)};`);
  w(`wall_thickness = ${f(chipParams.wallThickness)};`);
  w(`min_edge_spacing = ${f(chipParams.minEdgeSpacing)};`);
  if (pocket) {
    // Derived rather than fixed, so editing the slide thickness in OpenSCAD
    // moves the channels with the pocket floor instead of leaving them roofed.
    w('// The channels open onto the pocket floor, so this follows the slide.');
    w('split_height = base_thickness - (slide_thickness + slide_bond_gap);');
  } else {
    w(`split_height = ${f(chipParams.splitHeight)};`);
  }
  w();

  if (pocket) {
    w('/* [Glass slide] */');
    w(`slide_width = ${f(params.slide.widthMm)};`);
    w(`slide_length = ${f(params.slide.lengthMm)};`);
    w(`slide_thickness = ${f(params.slide.thicknessMm)};`);
    w('// Extra pocket size per side, so the glass drops in.');
    w(`slide_clearance = ${f(params.slide.clearanceMm)};`);
    w('// Extra pocket depth under the glass, for adhesive.');
    w(`slide_bond_gap = ${f(params.slide.bondGapMm)};`);
    w(`slide_offset_x = ${f(params.slide.offsetXMm)};`);
    w(`slide_offset_y = ${f(params.slide.offsetYMm)};`);
    w('// Ghost the glass in the preview. It is bought, not printed, so it is');
    w('// drawn with % and never reaches the rendered part.');
    w('show_slide = true;');
    w();
  }
  w('/* [Output] */');
  w('// "both" renders the assembled chip; "body" and "lid" render one piece.');
  w(
    `piece = "${chipParams.splitType === 'two-piece' ? 'both' : 'solid'}"; // [both, body, lid, solid]`,
  );
  w('// Exploded gap between the halves when piece = "both".');
  w('explode = 0;');
  w();
  w('/* [Quality] */');
  w('channel_fn = 24;');
  w('feature_fn = 32;');
  w();

  // --- channels -------------------------------------------------------------
  w('module channels() {');
  let emittedAny = false;

  for (const edge of graph.edges) {
    const solved = loft.edges.get(edge.id);
    if (!solved || solved.samples.length < 2) continue;

    const total = solved.samples.length;
    const count = Math.max(2, Math.min(stationsPerEdge, total));
    const picked = Array.from({ length: count }, (_, i) =>
      solved.samples[Math.round((i / (count - 1)) * (total - 1))],
    );

    w(`  // segment ${edge.id} — ${edge.crossSection}`);
    for (let i = 0; i < picked.length - 1; i += 1) {
      const a = picked[i];
      const b = picked[i + 1];
      const pa = placeChannel(edge.crossSection, a.widthMm, a.heightMm, chipParams.splitHeight);
      const pb = placeChannel(edge.crossSection, b.widthMm, b.heightMm, chipParams.splitHeight);

      w('  hull() {');
      w(
        '    ' +
          sectionAt(
            edge.crossSection,
            a.point.x,
            a.point.y,
            pa.centerZ,
            deg(a.tangent.x, a.tangent.y),
            a.widthMm,
            a.heightMm,
          ),
      );
      w(
        '    ' +
          sectionAt(
            edge.crossSection,
            b.point.x,
            b.point.y,
            pb.centerZ,
            deg(b.tangent.x, b.tangent.y),
            b.widthMm,
            b.heightMm,
          ),
      );
      w('  }');
      emittedAny = true;
    }
  }

  // Joints, matching the viewport's corner fill.
  for (const node of graph.nodes) {
    const touching = edgesFrom(adjacency, node.id);
    if (touching.length < 2 || node.type === 'chamber') continue;

    const edge = touching[0];
    const sample = sampleAtNode(loft, edge, node.id);
    if (!sample) continue;

    const place = placeChannel(
      edge.crossSection,
      sample.widthMm,
      sample.heightMm,
      chipParams.splitHeight,
    );

    w(`  // joint at ${node.id}`);
    if (edge.crossSection === 'round') {
      w(
        `  translate([${f(node.x)}, ${f(node.y)}, ${f(place.centerZ)}]) sphere(d = ${f(sample.widthMm)}, $fn = feature_fn);`,
      );
    } else {
      w(
        `  translate([${f(node.x)}, ${f(node.y)}, ${f(place.centerZ)}]) cylinder(h = ${f(place.halfHeight * 2)}, d = ${f(sample.widthMm)}, center = true, $fn = feature_fn);`,
      );
    }
    emittedAny = true;
  }

  if (!emittedAny) w('  // no channels drawn yet');
  w('}');
  w();

  // --- chambers -------------------------------------------------------------
  w('module chambers() {');
  const chambers = graph.nodes.filter((n) => n.type === 'chamber');
  if (chambers.length === 0) w('  // none');
  for (const node of chambers) {
    if (node.type !== 'chamber') continue;
    const touching = edgesFrom(adjacency, node.id);
    const edge = touching[0];
    const sample = edge ? sampleAtNode(loft, edge, node.id) : undefined;
    const place = placeChannel(
      edge?.crossSection ?? chipParams.defaultCrossSection,
      sample?.widthMm ?? chipParams.defaultChannelWidthMm,
      sample?.heightMm ?? chipParams.defaultChannelHeightMm,
      chipParams.splitHeight,
    );

    const body =
      node.shape === 'sphere'
        ? `sphere(d = ${f(node.sizeMm)}, $fn = feature_fn);`
        : `cylinder(h = ${f(node.sizeMm)}, d = ${f(node.sizeMm)}, center = true, $fn = feature_fn);`;
    w(`  translate([${f(node.x)}, ${f(node.y)}, ${f(place.centerZ)}]) ${body}`);
  }
  w('}');
  w();

  // --- ports ----------------------------------------------------------------
  const ports = graph.nodes.filter((n): n is PortNode => n.type === 'port');

  const channelFor = (node: { id: string }) => {
    const edge = edgesFrom(adjacency, node.id)[0];
    const sample = edge ? sampleAtNode(loft, edge, node.id) : undefined;
    return placeChannel(
      edge?.crossSection ?? chipParams.defaultCrossSection,
      sample?.widthMm ?? chipParams.defaultChannelWidthMm,
      sample?.heightMm ?? chipParams.defaultChannelHeightMm,
      chipParams.splitHeight,
    );
  };
  const channelZFor = (node: { id: string }): number => channelFor(node).centerZ;
  const lockFor = (node: PortNode) => {
    const place = channelFor(node);
    return luerLockLayout(
      node.customSpec as Record<string, unknown> | undefined,
      chipParams.baseThickness,
      place.centerZ + place.halfHeight,
    );
  };

  w('module port_cavities() {');
  if (ports.length === 0) w('  // none');
  let usedThreadNote = false;

  for (const node of ports) {
    const boss = specNumber(node.customSpec, 'bossHeightMm', 0);
    const top = chipParams.baseThickness + boss;
    // Female mouths run 0.01 mm past the face, as the STL's do: a cut that
    // ends exactly on the top face leaves coplanar faces, which OpenSCAD's
    // preview z-fights and a render can close with a skin.
    const mouth = top + 0.01;
    const channelZ = channelZFor(node);
    const at = `translate([${f(node.x)}, ${f(node.y)}, `;

    w(`  // ${node.portType} port at ${node.id}`);

    if (node.portType === 'luer' || node.portType === 'luer-lock') {
      const large = specNumber(node.customSpec, 'taperLargeDiameterMm', LUER_TAPER.taperLargeDiameterMm);
      const small = specNumber(node.customSpec, 'taperSmallDiameterMm', LUER_TAPER.taperSmallDiameterMm);
      const length = specNumber(node.customSpec, 'taperLengthMm', LUER_TAPER.taperLengthMm);
      const taperBottom = Math.max(channelZ, mouth - length);

      w(
        `  ${at}${f(taperBottom)}]) cylinder(h = ${f(mouth - taperBottom)}, d1 = ${f(small)}, d2 = ${f(large)}, $fn = feature_fn);`,
      );
      w(
        `  ${at}${f(channelZ - 0.01)}]) cylinder(h = ${f(taperBottom - channelZ + 0.02)}, d = ${f(node.diameterMm)}, $fn = feature_fn);`,
      );

      if (node.portType === 'luer-lock') {
        // The collar's groove around the hub, where the hub runs below the
        // chip face. The thread itself is in port_threads(), added back after
        // this cut.
        const lock = lockFor(node);
        if (lock.grooveBottomZ < chipParams.baseThickness) {
          const h = chipParams.baseThickness + 0.01 - lock.grooveBottomZ;
          w(`  ${at}${f(lock.grooveBottomZ)}]) difference() {`);
          w(`    cylinder(h = ${f(h)}, r = ${f(lock.grooveRadiusMm)}, $fn = feature_fn);`);
          w(`    translate([0, 0, -0.01]) cylinder(h = ${f(h + 0.02)}, r = ${f(lock.hubRadiusMm)}, $fn = feature_fn);`);
          w('  }');
        }
        usedThreadNote = true;
      }
    } else if (node.portType === 'luer-male' || node.portType === 'barb') {
      // Male fittings add material above the face (see port_male_fittings), so
      // all the cavity has to do is drive the bore up through it and out the tip.
      const spigot =
        node.portType === 'luer-male'
          ? specNumber(node.customSpec, 'taperLengthMm', LUER_TAPER.taperLengthMm)
          : specNumber(node.customSpec, 'barbLengthMm', 10.5);
      w(
        `  ${at}${f(channelZ - 0.01)}]) cylinder(h = ${f(top + spigot - channelZ + 0.02)}, d = ${f(node.diameterMm)}, $fn = feature_fn);`,
      );
    } else if (node.portType === 'syringe') {
      const barrel = specNumber(node.customSpec, 'barrelDiameterMm', 1.6);
      const depth = specNumber(node.customSpec, 'barrelDepthMm', 6);
      const bottom = Math.max(channelZ, mouth - depth);
      w(`  ${at}${f(bottom)}]) cylinder(h = ${f(mouth - bottom)}, d = ${f(barrel)}, $fn = feature_fn);`);
      w(
        `  ${at}${f(channelZ - 0.01)}]) cylinder(h = ${f(bottom - channelZ + 0.02)}, d = ${f(node.diameterMm)}, $fn = feature_fn);`,
      );
    } else {
      const outer = specNumber(node.customSpec, 'outerDiameterMm', 4);
      const depth = specNumber(node.customSpec, 'depthMm', 5);
      const bottom = Math.max(channelZ, mouth - depth);
      w(`  ${at}${f(bottom)}]) cylinder(h = ${f(mouth - bottom)}, d = ${f(outer)}, $fn = feature_fn);`);
      w(
        `  ${at}${f(channelZ - 0.01)}]) cylinder(h = ${f(bottom - channelZ + 0.02)}, d = ${f(node.diameterMm)}, $fn = feature_fn);`,
      );
    }
  }
  w('}');
  w();

  // --- bosses ---------------------------------------------------------------
  // A boss is a cylinder plus, when it has one, the concave fillet at its base:
  // a square with a circle taken out of its outer corner, revolved. The square
  // starts 0.01 mm under the face, as the STL's does, so the union with the
  // block has no coplanar face to close.
  w('module boss(r, h, fillet) {');
  w('  cylinder(h = h, r = r, $fn = feature_fn);');
  w('  if (fillet > 0)');
  w('    rotate_extrude($fn = feature_fn)');
  w('      difference() {');
  w('        translate([0, -0.01]) square([r + fillet, fillet + 0.01]);');
  w('        translate([r + fillet, fillet]) circle(r = fillet, $fn = feature_fn);');
  w('      }');
  w('}');
  w();
  w('module port_bosses() {');
  const withBoss = ports.filter((n) => specNumber(n.customSpec, 'bossHeightMm', 0) > 0);
  if (withBoss.length === 0) w('  // none');
  for (const node of withBoss) {
    const boss = specNumber(node.customSpec, 'bossHeightMm', 0);
    const radius =
      node.portType === 'luer-lock'
        ? lockFor(node).hubRadiusMm
        : node.portType === 'luer' || node.portType === 'luer-male'
          ? specNumber(node.customSpec, 'taperLargeDiameterMm', LUER_TAPER.taperLargeDiameterMm) / 2 + 0.8
          : node.portType === 'barb'
            ? specNumber(node.customSpec, 'barbCrestDiameterMm', 3.5) / 2 + 0.8
            : node.portType === 'syringe'
              ? specNumber(node.customSpec, 'barrelDiameterMm', 1.6) / 2 + 0.8
              : specNumber(node.customSpec, 'outerDiameterMm', 4) / 2 + 0.8;
    const fillet = bossFilletMm(node.portType, node.customSpec);
    w(
      `  translate([${f(node.x)}, ${f(node.y)}, ${f(chipParams.baseThickness)}]) boss(r = ${f(radius)}, h = ${f(boss)}, fillet = ${f(fillet)});`,
    );
  }
  w('}');
  w();

  // --- male fittings --------------------------------------------------------
  // The cone of a `luer-male` and the ridges of a `barb` stand above the face,
  // so they are added like a boss rather than cut like a socket.
  w('module port_male_fittings() {');
  const male = ports.filter((n) => n.portType === 'luer-male' || n.portType === 'barb');
  if (male.length === 0) w('  // none');
  for (const node of male) {
    const base = chipParams.baseThickness + specNumber(node.customSpec, 'bossHeightMm', 0);
    const at = `translate([${f(node.x)}, ${f(node.y)}, `;
    w(`  // ${node.portType} fitting at ${node.id}`);

    if (node.portType === 'luer-male') {
      const large = specNumber(node.customSpec, 'taperLargeDiameterMm', LUER_TAPER.taperLargeDiameterMm);
      const small = specNumber(node.customSpec, 'taperSmallDiameterMm', LUER_TAPER.taperSmallDiameterMm);
      const length = specNumber(node.customSpec, 'taperLengthMm', LUER_TAPER.taperLengthMm);
      w(
        `  ${at}${f(base)}]) cylinder(h = ${f(length)}, d1 = ${f(large)}, d2 = ${f(small)}, $fn = feature_fn);`,
      );
    } else {
      const crest = specNumber(node.customSpec, 'barbCrestDiameterMm', 3.5);
      const stem = specNumber(node.customSpec, 'stemDiameterMm', 2.9);
      const length = specNumber(node.customSpec, 'barbLengthMm', 10.5);
      const count = Math.max(1, Math.round(specNumber(node.customSpec, 'barbCount', 3)));
      const seg = length / count;

      w(`  ${at}${f(base)}]) cylinder(h = ${f(length)}, d = ${f(stem)}, $fn = feature_fn);`);
      for (let i = 0; i < count; i += 1) {
        // Widest at the bottom of each ridge, tapering back to the stem going
        // up: the abrupt shoulder faces the chip, so the tube has to stretch
        // back over the crest to come off.
        w(
          `  ${at}${f(base + i * seg)}]) cylinder(h = ${f(seg)}, d1 = ${f(crest)}, d2 = ${f(stem)}, $fn = feature_fn);`,
        );
      }
    }
  }
  w('}');
  w();

  // --- luer-lock threads ----------------------------------------------------
  // A rib on the outside of each hub, as a twisted extrusion of a sector of the
  // ring between the hub and the thread's major diameter. Negative twist makes
  // it right-handed, like the STL's. Unioned on after the cavity is cut, since
  // part of it stands in the collar groove.
  const locks = ports.filter((n) => n.portType === 'luer-lock');
  w('module port_threads() {');
  if (locks.length === 0) w('  // none');
  for (const node of locks) {
    const lock = lockFor(node);
    const h = lock.hubTopZ - lock.grooveBottomZ;
    if (h <= 0.1) continue;
    // Axial thickness of the rib, matched to the mid-height of the STL's
    // trapezoidal profile, then turned into the sector angle that gives it.
    const halfAxial = Math.min(lock.pitchMm * 0.35, lock.pitchMm / 2 - 0.01);
    const sweep = Math.min(300, ((halfAxial * 1.45) / lock.pitchMm) * 360);
    const inner = lock.hubRadiusMm - 0.05;
    const arc = (radius: number, reverse: boolean) => {
      const steps = 12;
      const pts = Array.from({ length: steps + 1 }, (_, i) => {
        const a = (((reverse ? steps - i : i) / steps) * sweep * Math.PI) / 180;
        return `[${f(Math.cos(a) * radius)}, ${f(Math.sin(a) * radius)}]`;
      });
      return pts.join(', ');
    };
    w(`  // thread on ${node.id}: ${f(h / lock.pitchMm)} turn(s) at ${f(lock.pitchMm)} mm lead`);
    w(
      `  translate([${f(node.x)}, ${f(node.y)}, ${f(lock.grooveBottomZ)}]) ` +
        `linear_extrude(height = ${f(h)}, twist = ${f((-360 * h) / lock.pitchMm)}, slices = 48, convexity = 4)`,
    );
    w(`    polygon([${arc(lock.majorRadiusMm, false)}, ${arc(inner, true)}]);`);
  }
  w('}');
  w();

  // --- drainage vents -------------------------------------------------------
  // Straight bores from the channel up through the top face, overshooting it
  // by 0.5 mm so the cut breaks through — the same bores buildChip drills.
  const vents = (options.drainageVents ?? []).flatMap((vent) => {
    const node = graph.nodes.find((n) => n.id === vent.nodeId);
    return node ? [{ vent, node }] : [];
  });
  w('module drainage_vents() {');
  if (vents.length === 0) w('  // none');
  for (const { vent, node } of vents) {
    const bottom = channelZFor(node) - 0.01;
    w(
      `  translate([${f(node.x)}, ${f(node.y)}, ${f(bottom)}]) ` +
        `cylinder(h = base_thickness + 0.5 - ${f(bottom)}, d = ${f(vent.diameterMm)}, $fn = channel_fn);`,
    );
  }
  w('}');
  w();

  // --- glass slide ----------------------------------------------------------
  if (pocket) {
    w('// The pocket the glass drops into. Its floor is the channels\' open face.');
    w('module slide_pocket() {');
    w('  translate([chip_width / 2 + slide_offset_x - (slide_width + 2 * slide_clearance) / 2,');
    w('             chip_length / 2 + slide_offset_y - (slide_length + 2 * slide_clearance) / 2,');
    w('             split_height])');
    w('    cube([slide_width + 2 * slide_clearance, slide_length + 2 * slide_clearance,');
    w('          slide_thickness + slide_bond_gap + 1]);');
    w('}');
    w();
    w('module glass_slide() {');
    w('  translate([chip_width / 2 + slide_offset_x - slide_width / 2,');
    w('             chip_length / 2 + slide_offset_y - slide_length / 2,');
    w('             split_height + slide_bond_gap])');
    w('    cube([slide_width, slide_length, slide_thickness]);');
    w('}');
    w();
  }

  // --- assembly -------------------------------------------------------------
  w('module chip_solid() {');
  w('  union() {');
  w('    difference() {');
  w('      union() {');
  w(`        cube([chip_width, chip_length, base_thickness]);`);
  w('        port_bosses();');
  w('        port_male_fittings();');
  w('      }');
  w('      union() {');
  w('        channels();');
  w('        chambers();');
  w('        port_cavities();');
  w('        drainage_vents();');
  if (pocket) w('        slide_pocket();');
  w('      }');
  w('    }');
  w('    port_threads();');
  w('  }');
  w('}');
  w();

  const tall = chipParams.baseThickness * 4 + 20;
  w('// Half-spaces used to cut the two-piece split.');
  w('module below_split() {');
  w(
    `  translate([-1, -1, -${f(tall)}]) cube([chip_width + 2, chip_length + 2, ${f(tall)} + split_height]);`,
  );
  w('}');
  w('module above_split() {');
  w(
    `  translate([-1, -1, split_height]) cube([chip_width + 2, chip_length + 2, ${f(tall)}]);`,
  );
  w('}');
  w();
  w('module body_piece() { intersection() { chip_solid(); below_split(); } }');
  w('module lid_piece()  { intersection() { chip_solid(); above_split(); } }');
  w();
  w('if (piece == "solid") {');
  w('  chip_solid();');
  w('} else if (piece == "body") {');
  w('  body_piece();');
  w('} else if (piece == "lid") {');
  w('  lid_piece();');
  w('} else {');
  w('  body_piece();');
  w('  translate([0, 0, explode]) lid_piece();');
  w('}');

  if (pocket) {
    w();
    w('if (show_slide) %glass_slide();');
  }

  if (usedThreadNote) {
    w();
    w('// ---------------------------------------------------------------------');
    w('// Note on luer-lock threads');
    w('//');
    w('// The boss is the hub the socket runs down; port_threads() puts a');
    w('// single-start rib on its outside, and the male collar screws down over');
    w('// both. It is an approximation of the two-start ISO 80369-7 form, built');
    w('// as a twisted extrusion, and the STL sweeps a slightly different');
    w('// (trapezoidal) profile. Test-fit either before relying on it.');
    w('// ---------------------------------------------------------------------');
  }

  return `${out.join('\n')}\n`;
}
